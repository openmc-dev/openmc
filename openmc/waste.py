def _get_excluded_daughters(chain, plus_parents):
    """Find daughter nuclides covered by '+' clearance values.

    For each '+' parent in the chain, recursively walks the decay chain and
    collects all daughters whose half-life is shorter than the original
    parent's. These daughters are in secular equilibrium and their activity
    is already accounted for by the parent's '+' clearance value.

    Parameters
    ----------
    chain : openmc.deplete.Chain
        Depletion chain with decay data.
    plus_parents : set of str
        Nuclide names whose clearance values include daughters.

    Returns
    -------
    set of str
        Nuclide names to exclude from the sum-of-fractions.

    """
    excluded = set()
    for parent_name in plus_parents:
        if parent_name not in chain.nuclide_dict:
            continue
        parent_nuc = chain[parent_name]
        if parent_nuc.half_life is None or parent_nuc.half_life <= 0:
            continue
        _walk_daughters(
            chain, parent_name, parent_nuc.half_life, excluded, set()
        )
    return excluded


def _walk_daughters(chain, name, parent_half_life, excluded, visited):
    """Recursively collect daughters in secular equilibrium.

    Walks the decay chain from *name*, adding each radioactive daughter to
    *excluded* as long as its half-life is shorter than *parent_half_life*
    (the original '+' parent). Stops descending a branch when a daughter's
    half-life exceeds the parent's.

    """
    if name in visited:
        return
    visited.add(name)

    if name not in chain.nuclide_dict:
        return
    nuc = chain[name]

    for mode in nuc.decay_modes:
        daughter = mode.target
        if daughter is None or daughter in visited:
            continue
        if daughter not in chain.nuclide_dict:
            continue
        daughter_nuc = chain[daughter]
        if daughter_nuc.half_life is None or daughter_nuc.half_life <= 0:
            continue
        if daughter_nuc.half_life < parent_half_life:
            excluded.add(daughter)
            _walk_daughters(
                chain, daughter, parent_half_life, excluded, visited
            )


def _waste_classification(mat: openmc.Material, metal: bool = True) -> str:
    """Classify a material for near-surface waste disposal.

    This method determines a waste classification for a material based on the
    NRC regulations (10 CFR 61.55).

    Parameters
    ----------
    mat : openmc.Material
        The material to classify.
    metal : bool, optional
        Whether or not the material is in metal form. This changes the
        acceptable limits in Tables 1 and 2 for certain nuclides.

    Returns
    -------
    str
        The waste disposal classification, which can be "Class A", "Class B",
        "Class C", or "GTCC" (greater than class C).

    """
    # Determine metrics based on Tables 1 and 2 using sum of fractions rule for
    # mixture of radionuclides from §61.55(a)(7)
    ratio1 = _waste_disposal_rating(mat, 'NRC_long', metal=metal)
    ratio2 = [
        _waste_disposal_rating(mat, 'NRC_short_A', metal=metal),
        _waste_disposal_rating(mat, 'NRC_short_B', metal=metal),
        _waste_disposal_rating(mat, 'NRC_short_C', metal=metal),
    ]

    # Determine which nuclides are present in Table 1 and Table 2
    table1_nuclides_present = (ratio1 > 0.0)
    table2_nuclides_present = any(x > 0.0 for x in ratio2)

    # Helper function for classifying based on Table 2
    def classify_table2(col1, col2, col3):
        if col1 < 1.0:
            return "Class A"
        elif col2 < 1.0:
            return "Class B"
        elif col3 < 1.0:
            return "Class C"
        else:
            return "GTCC"

    if table1_nuclides_present and table2_nuclides_present:
        # Classification based on §61.55(a)(5)
        if ratio1 < 0.1:
            return classify_table2(*ratio2)
        elif ratio1 < 1.0:
            return "Class C" if ratio2[2] < 1.0 else "GTCC"
        else:
            return "GTCC"

    elif table1_nuclides_present:
        # Classification based on §61.55(a)(3)
        if ratio1 < 0.1:
            return "Class A"
        elif ratio1 < 1.0:
            return "Class C"
        else:
            return "GTCC"

    elif table2_nuclides_present:
        # Classification based on §61.55(a)(4)
        return classify_table2(*ratio2)

    else:
        # Classification based on §61.55(a)(6)
        return "Class A"


